def greg_to_lunar(year, month, day):
    """Convert Gregorian to lunar date"""
    if year not in LUNAR_INFO:
        return (year, month, day, False)

    lny_m, lny_d, leap, months_str = LUNAR_INFO[year]
    lny_date = date(year, lny_m, lny_d)
    lny_doy = (lny_date - date(year, 1, 1)).days
    birth_doy = (date(year, month, day) - date(year, 1, 1)).days
    months = [30 if c == '1' else 29 for c in months_str]

    if birth_doy < lny_doy:
        # Previous lunar year
        prev = LUNAR_INFO.get(year - 1)
        if not prev:
            return (year - 1, 12, birth_doy + 1, False)
        prev_m, prev_d, prev_leap, prev_str = prev
        prev_lny_date = date(year - 1, prev_m, prev_d)
        prev_lny_doy = (prev_lny_date - date(year - 1, 1, 1)).days
        prev_year_end = (date(year - 1, 12, 31) - date(year - 1, 1, 1)).days
        days_from = (prev_year_end - prev_lny_doy) + birth_doy + 1
        prev_months = [30 if c == '1' else 29 for c in prev_str]
        return _find_month(days_from, prev_months, prev_leap, year - 1)
    else:
        days_from = birth_doy - lny_doy + 1
        return _find_month(days_from, months, leap, year)

def _find_month(days, months, leap, lyear):
    lm, ld, is_leap = 0, 0, False
    for i, mlen in enumerate(months):
        if days <= mlen:
            lm = i + 1
            ld = days
            if leap > 0:
                if lm > leap:
                    lm -= 1
                elif lm == leap and i >= leap:
                    is_leap = True
            break
        days -= mlen
    if lm == 0:
        lm, ld = 12, max(days, 1)
    return (lyear, lm, max(ld, 1), is_leap)

